/* Service worker.
   campaign/ is small (under 1 MB) so it is precached in full and works fully
   offline. vault/ is ~192 MB across 41k files, so it is cached lazily as pages
   are actually opened — anything you have read once stays available offline. */
const VERSION = 'v125';
const PREFIX = 'saeroth-' + new URL(self.registration.scope).pathname + '-';
const SHELL = PREFIX + 'shell-' + VERSION;
const NOTES = PREFIX + 'notes';

const SHELL_FILES = [
  '', 'index.html', 'app.js', 'styles.css', 'marked.min.js',
  'polish.js', 'manifest.webmanifest', 'index-campaign.json', 'icons/icon.svg',
  // the relations web's optional map mode; both are generated by
  // tools/build_atlas_lore.py and are useless without each other
  'nation-positions.json', 'atlas/political.webp', 'atlas-host.js', 'atlas/lore-index.json',
];

self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const cache = await caches.open(SHELL);
    const base = new URL('./', self.registration.scope).pathname;
    await cache.addAll(SHELL_FILES.map((f) => base + f));
    // precache every campaign note
    try {
      const list = await (await fetch(base + 'precache.json')).json();
      const notes = await caches.open(NOTES);
      await Promise.all(list.map((p) =>
        notes.add(base + 'content/' + p.split('/').map(encodeURIComponent).join('/')).catch(() => {})));
    } catch (_) { /* offline install: shell only */ }
    self.skipWaiting();
  })());
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) {
      if (k.startsWith(PREFIX) && k !== NOTES && !k.endsWith(VERSION)) await caches.delete(k);
    }
    await self.clients.claim();
  })());
});

/* The app asks for this on boot and prints it in the sidebar. Without it there
   is no way to tell a stale device from a stale deploy — an installed
   home-screen app serving an old note looks exactly like a bad edit. Replies
   down the caller's MessageChannel port when there is one. */
self.addEventListener('message', (e) => {
  if (e.data !== 'version') return;
  const reply = { version: VERSION };
  if (e.ports && e.ports[0]) e.ports[0].postMessage(reply);
  else if (e.source) e.source.postMessage(reply);
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;

  /* /players/ is a separate hand-written site that is meant to have no
     service worker at all. This one's scope covers it regardless, and its
     documents live under players/content/, which the notes rule below matched
     on the path alone — so the players' page was being served out of a cache
     it never asked for. A phone would show a months-old copy of a document
     and 404 on art added to it since, which is exactly what it looks like
     when somebody has made a bad edit. Hand the whole subtree back to the
     browser.

     Matched against the worker's own scope rather than as a substring,
     because campaign/players/<name>/ is a real folder of notes and those do
     belong in the cache. */
  const players = new URL('./players/', self.registration.scope).pathname;
  if (url.pathname.startsWith(players)) return;

  // Atlas art and detail tiles are fetched only when viewed. Never substitute
  // wiki HTML for an unavailable image or script while offline.
  const atlas = new URL('./atlas/', self.registration.scope).pathname;
  if (url.pathname.startsWith(atlas)) {
    e.respondWith((async () => {
      const name = PREFIX + 'atlas-' + VERSION;
      const hit = await readCache(name, req);
      if (hit) return hit;
      try {
        const res = await fetch(req);
        await remember(name, req, res);
        return res;
      } catch (_) { return new Response('Atlas asset unavailable offline', {status: 503}); }
    })());
    return;
  }

  // Notes and the vault index: cache-first, then network, then remember it.
  if (/\/content\/|index-vault\.json$/.test(req.url)) {
    e.respondWith((async () => {
      const hit = await readCache(NOTES, req);
      if (hit) return hit;
      try {
        const res = await fetch(req);
        await remember(NOTES, req, res);
        return res;
      } catch (err) {
        return new Response('# Offline\n\nThis note has not been opened before, so it is not cached yet.',
          { headers: { 'Content-Type': 'text/markdown' } });
      }
    })());
    return;
  }

  // App shell: network-first so updates land, falling back to cache offline.
  e.respondWith((async () => {
    try {
      const res = await fetch(req);
      await remember(SHELL, req, res);
      return res;
    } catch (err) {
      return (await readCache(SHELL, req)) ||
             (await readCache(SHELL, new URL('./index.html', self.registration.scope).pathname)) || new Response('Unavailable offline', {status:503});
    }
  })());
});

// Storage is optional. A full or disabled cache must never discard a network response.
async function readCache(name, req) {
  try { return await (await caches.open(name)).match(req); } catch (_) { return undefined; }
}
async function remember(name, req, response) {
  if (!response.ok) return;
  try { await (await caches.open(name)).put(req, response.clone()); } catch (_) { /* quota/private browsing */ }
}
